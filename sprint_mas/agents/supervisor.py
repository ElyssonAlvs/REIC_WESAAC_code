"""Agente Supervisor de Governança e Qualidade (Supervisor Node) do Sprint Planning MAS."""

import json
import re
from typing import Any, Optional, Union

from langchain_core.language_models import BaseChatModel
from langchain_core.messages import AIMessage
from pydantic import BaseModel, ConfigDict, Field

from sprint_mas.agents.validator import ValidationReport, audit_sprint_state
from sprint_mas.llm_factory import get_llm
from sprint_mas.prompts import get_agent_prompt_template
from sprint_mas.state import Allocation, SprintPlan, SprintState, Task


class SupervisorOutput(BaseModel):
    """Structured output schema for the Agile Governance Supervisor Agent."""

    model_config = ConfigDict(extra="forbid")

    is_approved: bool = Field(
        ...,
        description="True if the sprint plan is homologated and approved for execution, False otherwise.",
    )
    validation_errors: list[str] = Field(
        default_factory=list,
        description="List of technical non-compliances, capacity overloads, or causal violations detected.",
    )
    sprint_summary: str = Field(
        ...,
        description="Executive summary of the audited sprint plan and team feasibility.",
    )
    recommendations: str = Field(
        ...,
        description="Technical, architectural, and operational recommendations for sprint execution.",
    )


def _clean_json_markdown(content: str) -> str:
    """Extracts clean JSON content if wrapped in markdown code fences."""
    content_str = content.strip()
    match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", content_str, re.IGNORECASE)
    if match:
        return match.group(1).strip()
    return content_str


def validate_supervisor_decision(
    state: Union[SprintState, dict[str, Any]],
    decision: SupervisorOutput,
    report: Optional[ValidationReport] = None,
    sprint_days: int = 10,
    points_per_day: float = 2.0,
) -> None:
    """Guardian of Server Authority: audits the sprint state and verifies supervisor decision integrity.

    Enforces Server Authority: an invalid sprint state can NEVER be marked as is_approved=True.

    Args:
        state: Shared SprintState or dictionary containing tasks, team, and allocations.
        decision: SupervisorOutput generated by the LLM or agent.
        report: Optional pre-computed ValidationReport from audit_sprint_state.
        sprint_days: Sprint duration in business days (default: 10, must be > 0).
        points_per_day: Nominal story points rate per full-time day (default: 2.0, must be > 0).

    Raises:
        ValueError: If the sprint state has violations but decision.is_approved is True.
    """
    if report is None:
        report = audit_sprint_state(
            state=state,
            sprint_days=sprint_days,
            points_per_day=points_per_day,
        )

    if not report.is_valid and decision.is_approved:
        raise ValueError(
            f"Server Authority violation: Supervisor approved an invalid sprint plan "
            f"with {len(report.violations)} violation(s):\n"
            + "\n".join(f"- {v}" for v in report.violations)
        )


def deterministic_supervisor_decision(
    state: Union[SprintState, dict[str, Any]],
    report: Optional[ValidationReport] = None,
    sprint_days: int = 10,
    points_per_day: float = 2.0,
    sprint_goal: str = "Deliver prioritized and feasible sprint backlog.",
) -> SupervisorOutput:
    """Produces an objective, deterministic governance decision based strictly on state audit."""
    if report is None:
        report = audit_sprint_state(
            state=state,
            sprint_days=sprint_days,
            points_per_day=points_per_day,
        )

    tasks_raw = state.get("prioritized_tasks") or state.get("backlog") or []
    tasks = [t if isinstance(t, Task) else Task(**t) for t in tasks_raw]
    total_pts = sum(t.story_points for t in tasks)

    if report.is_valid:
        summary = (
            f"Sprint plan approved: {len(tasks)} tasks scheduled with {total_pts} "
            f"canonical story points across {len(report.allocated_by_dev)} developers. "
            f"Sprint goal: '{sprint_goal}'."
        )
        recommendations = (
            "Proceed with sprint execution according to allocated tasks and causal DAG dependencies. "
            "Continuously monitor developer workloads to prevent mid-sprint bottlenecks."
        )
        return SupervisorOutput(
            is_approved=True,
            validation_errors=[],
            sprint_summary=summary,
            recommendations=recommendations,
        )
    else:
        summary = (
            f"Sprint plan rejected due to {len(report.violations)} validation violation(s). "
            f"Cannot commit to sprint goal: '{sprint_goal}'."
        )
        recommendations = (
            "Resolve capacity overloads, skill mismatches, or causal DAG dependency violations "
            "before resubmitting the sprint plan."
        )
        return SupervisorOutput(
            is_approved=False,
            validation_errors=list(report.violations),
            sprint_summary=summary,
            recommendations=recommendations,
        )


def supervisor_node(
    state: SprintState,
    llm: Optional[BaseChatModel] = None,
    strict: bool = False,
    sprint_days: int = 10,
    points_per_day: float = 2.0,
    sprint_goal: str = "Deliver prioritized and feasible sprint backlog.",
) -> dict[str, Any]:
    """LangGraph node for the Agile Governance & Quality Supervisor Agent.

    Performs executive validation, BART prompt deliberation, Server Authority enforcement,
    and final SprintPlan materialization.

    Args:
        state: Shared SprintState blackboard.
        llm: Optional BaseChatModel instance.
        strict: If True, raises ValueError on LLM failure or approval hallucination.
        sprint_days: Sprint duration in business days (default: 10, must be > 0).
        points_per_day: Nominal story points rate per full-time day (default: 2.0, must be > 0).
        sprint_goal: Sprint objective string.

    Returns:
        dict[str, Any]: State delta containing 'sprint_plan', 'validation_errors', and 'messages'.

    Raises:
        ValueError: If input state is invalid, or if strict=True and deliberation fails.
    """
    report = audit_sprint_state(
        state=state,
        sprint_days=sprint_days,
        points_per_day=points_per_day,
    )

    allocations_raw = state.get("allocations", [])
    allocations = [a if isinstance(a, Allocation) else Allocation(**a) for a in allocations_raw]
    allocations_json = json.dumps([a.model_dump() for a in allocations], indent=2, ensure_ascii=False)
    feasibility_json = json.dumps(report.model_dump(), indent=2, ensure_ascii=False)

    prompt_template = get_agent_prompt_template("supervisor")
    formatted_messages = prompt_template.format_messages(
        allocations_json=allocations_json,
        feasibility_json=feasibility_json,
        sprint_goal=sprint_goal,
    )

    decision: Optional[SupervisorOutput] = None
    try:
        active_llm = llm or get_llm(temperature=0.0)
        response = active_llm.invoke(formatted_messages)
        response_text = _clean_json_markdown(str(response.content))
        data = json.loads(response_text)
        decision = SupervisorOutput(**data)
        validate_supervisor_decision(
            state=state,
            decision=decision,
            report=report,
            sprint_days=sprint_days,
            points_per_day=points_per_day,
        )
    except Exception as exc:
        if strict:
            raise ValueError(
                f"Supervisor deliberation failed (strict=True): {exc}"
            ) from exc
        decision = deterministic_supervisor_decision(
            state=state,
            report=report,
            sprint_days=sprint_days,
            points_per_day=points_per_day,
            sprint_goal=sprint_goal,
        )

    tasks_raw = state.get("prioritized_tasks") or state.get("backlog") or []
    canonical_tasks = [t if isinstance(t, Task) else Task(**t) for t in tasks_raw]

    if decision.is_approved and report.is_valid:
        # Server authority: calculate total_points strictly from canonical Task.story_points
        total_points = sum(t.story_points for t in canonical_tasks)
        sprint_plan = SprintPlan(
            sprint_name="Sprint 1",
            sprint_goal=sprint_goal,
            tasks=canonical_tasks,
            allocations=allocations,
            total_points=total_points,
            summary=decision.sprint_summary,
        )
        status_str = "APPROVED"
        validation_errors: list[str] = []
    else:
        sprint_plan = None
        status_str = "REJECTED"
        validation_errors = list(report.violations) if report.violations else list(decision.validation_errors)

    ai_message = AIMessage(
        content=(
            f"### Supervisor Agent Deliberation\n\n"
            f"**Status**: {status_str}\n"
            f"**Goal**: {sprint_goal}\n"
            f"**Approved**: {decision.is_approved}\n\n"
            f"**Summary**:\n{decision.sprint_summary}\n\n"
            f"**Recommendations**:\n{decision.recommendations}"
        )
    )

    return {
        "sprint_plan": sprint_plan,
        "validation_errors": validation_errors,
        "messages": [ai_message],
    }


governance_supervisor_node = supervisor_node
